    private string GetArrayTypeName()
    {
        return UsesEffectSchema ? "ReadonlyArray" : "Array";
    }

    /// <summary>
    /// Builds the Effect Schema expression for a value, such as a list element or an
    /// endpoint request/response. Optional types become <c>NullOr</c> rather than an
    /// optional property, because there is no object key to omit.
    /// </summary>
    public string GetSchemaValueExpression(IDataType dataType)
    {
        // Endpoint types always come from another generated file, so direct references
        // are safe and avoid an unnecessary Schema.suspend wrapper.
        string expression = GetSchemaTypeExpression(dataType, deferUserTypes: false);
        if (dataType is IOptionalDataType)
            expression = $"Schema.NullOr({expression})";
        return expression;
    }

    private string GetSchemaPropertyExpression(BuiltProperty property)
    {
        IDataType dataType = property.Node.BuiltType!;
        string expression = GetSchemaTypeExpression(dataType, deferUserTypes: true);

        if (dataType is IOptionalDataType)
        {
            return GetPresence(property) switch
            {
                PropertyPresence.Optional => $"Schema.optional({expression})",
                PropertyPresence.Nullable => $"Schema.NullOr({expression})",
                _ => $"Schema.optional(Schema.NullOr({expression}))"
            };
        }

        if (property.Node.Value is not null && property.Value is SomeDataValue some)
            return $"Schema.optionalWith({expression}, {{ default: () => {some.Value}, exact: true }})";

        return expression;
    }

    private string GetSchemaTypeExpression(IDataType dataType, bool deferUserTypes)
    {
        switch (dataType)
        {
            case AnyType:
                return "Schema.Any";
            case BooleanType:
                return "Schema.Boolean";
            case DateType:
                // Dates stay ISO 8601 strings, the same wire format the class output uses.
                return "Schema.String";
            case FloatType:
                return "Schema.Number";
            case IntegerType:
                return "Schema.Int";
            case Integer64Type:
                return "Schema.BigIntFromNumber";
            case ListType listType:
                return $"Schema.Array({GetSchemaValueExpression(listType.InnerType, deferUserTypes)})";
            case MapType mapType:
                return $"Schema.Record({{ key: Schema.String, value: {GetSchemaValueExpression(mapType.InnerTypeB, deferUserTypes)} }})";
            case SetType setType:
                return $"Schema.Array({GetSchemaValueExpression(setType.InnerType, deferUserTypes)})";
            case StringType:
                return "Schema.String";
            case TimeType:
                return "Schema.Number";
            case UuidType:
                return "Schema.UUID";
            case UrlType:
                return "Schema.String";
            case EnumType enumType:
                string enumName = GetSimpleUserTypeName(enumType);
                return enumType.OwnedEnum.Flags == true || enumType.OwnedEnum.IsString
                    ? $"{enumName}Schema"
                    : $"Schema.Enums({enumName})";
            case ObjectType or UnionType:
                // Definition order must not matter, and definitions may be recursive.
                string reference = GetSimpleUserTypeName((IUserDataType)dataType);
                return deferUserTypes ? $"Schema.suspend(() => {reference})" : reference;
            default:
                throw new ArgumentOutOfRangeException(nameof(dataType));
        }
    }

    private string GetSchemaValueExpression(IDataType dataType, bool deferUserTypes)
    {
        string expression = GetSchemaTypeExpression(dataType, deferUserTypes);
        if (dataType is IOptionalDataType)
            expression = $"Schema.NullOr({expression})";
        return expression;
    }

    private static string GetCompiledPropertyKey(string name)
    {
        if (name.Length > 0 && (char.IsLetter(name[0]) || name[0] is '_' or '$'))
        {
            bool isValid = true;
            for (var nameIdx = 1; nameIdx < name.Length; nameIdx++)
            {
                char character = name[nameIdx];
                if (!char.IsLetterOrDigit(character) && character is not '_' and not '$')
                {
                    isValid = false;
                    break;
                }
            }

            if (isValid)
                return name;
        }

        return $"'{name.Replace("\\", "\\\\").Replace("'", "\\'")}'";
    }

    public StringBuilder AppendDescriptionComment(StringBuilder sb, INodeDescription node, int indentation = 0)
    {
        List<string> descriptionLines = [];
        List<string> metadataLines = [];

        if (!string.IsNullOrEmpty(node.Description))
            descriptionLines.AddRange(node.Description.Split('\n'));

        if (node is PropertyNode propertyNode)
        {
            // Say how an optional value behaves only when the description doesn't already.
            bool isOptional = propertyNode.BuiltType is IOptionalDataType;
            if (isOptional && descriptionLines.Count == 0)
            {
                metadataLines.Add(propertyNode.Presence switch
                {
                    PropertyPresence.Optional => "May be absent; never null.",
                    PropertyPresence.Nullable => "Always present; may be null.",
                    _ => "Optional property."
                });
            }

            if (propertyNode.Validation is { } validation)
            {
                if (validation.Min is { } min)
                {
                    string inclusive = validation.MinInclusive ? "inclusive" : "exclusive";
                    metadataLines.Add($"Minimum value: {min} ({inclusive}).");
                }
                if (validation.Max is { } max)
                {
                    string inclusive = validation.MaxInclusive ? "inclusive" : "exclusive";
                    metadataLines.Add($"Maximum value: {max} ({inclusive}).");
                }
                if (!string.IsNullOrEmpty(validation.PatternRaw))
                    metadataLines.Add($"Pattern: {validation.PatternRaw}.");
            }
        }

        if (descriptionLines.Count == 0 && metadataLines.Count == 0)
            return sb;

        for (int indent = 0; indent < indentation; indent++)
            sb.Append("    ");
        sb.AppendLine("/**");

        foreach (string line in descriptionLines)
        {
            for (int indent = 0; indent < indentation; indent++)
                sb.Append("    ");
            sb.AppendLine($" * {line}");
        }

        foreach (string line in metadataLines)
        {
            for (int indent = 0; indent < indentation; indent++)
                sb.Append("    ");
            sb.AppendLine($" * {line}");
        }

        for (int indent = 0; indent < indentation; indent++)
            sb.Append("    ");
        sb.AppendLine(" */");

        return sb;
    }

    private Dictionary<string, HashSet<string>> BuildTypeScriptImportMap(BuiltFile file)
    {
        var map = new Dictionary<string, HashSet<string>>(StringComparer.OrdinalIgnoreCase);

        // Collect from definitions
        foreach (BuiltDefinition def in file.Definitions)
        foreach (BuiltProperty prop in def.Properties)
            CollectImportsForPropertyType(file, prop.Node.BuiltType!, map);

        // Constants are emitted as values in Effect Schema mode, so their types must be imported too.
        // They only need the enum/definition symbol, not a generated flags schema const.
        if (UsesEffectSchema)
            foreach (BuiltDefinition def in file.Definitions)
            foreach (BuiltConstant constant in def.Constants)
                CollectImportsForPropertyType(file, constant.Node.BuiltType!, map, includeSchemaSymbols: false);

        // Union variants may live in other files.
        foreach (UnionNode union in file.Unions)
        foreach (ObjectType variant in union.Variants.Values)
            CollectImportsForPropertyType(file, variant, map, includeSchemaSymbols: false);

        // Collect from services
        foreach (BuiltService service in file.Services)
        foreach (BuiltEndpoint endpoint in service.Endpoints)
        {
            CollectImportsForPropertyType(file, endpoint.Node.BuiltRequestType!, map);
            CollectImportsForPropertyType(file, endpoint.Node.BuiltResponseType!, map);
        }

        return map;
    }

    private void CollectImportsForPropertyType(
        BuiltFile currentFile,
        IDataType type,
        Dictionary<string, HashSet<string>> map,
        bool includeSchemaSymbols = true)
    {
        switch (type)
        {
            case ListType listType:
                CollectImportsForPropertyType(currentFile, listType.InnerType, map, includeSchemaSymbols);
                break;
            case SetType setType:
                CollectImportsForPropertyType(currentFile, setType.InnerType, map, includeSchemaSymbols);
                break;
            case MapType mapType:
                CollectImportsForPropertyType(currentFile, mapType.InnerTypeA, map, includeSchemaSymbols);
                CollectImportsForPropertyType(currentFile, mapType.InnerTypeB, map, includeSchemaSymbols);
                break;
            case IUserDataType userType:
            {
                string symbol = GetSimpleUserTypeName(userType);
                string targetFile = GetBuiltFileNameForUserType(userType);
                // Skip self-file
                if (string.Equals(targetFile, currentFile.Name, StringComparison.OrdinalIgnoreCase))
                    return;

                if (!map.TryGetValue(targetFile, out var symbols))
                {
                    symbols = new HashSet<string>(StringComparer.Ordinal);
                    map[targetFile] = symbols;
                }
                symbols.Add(symbol);

                if (includeSchemaSymbols && UsesEffectSchema &&
                    userType is EnumType { OwnedEnum.Flags: true } or EnumType { OwnedEnum.IsString: true })
                    symbols.Add($"{symbol}Schema");
                break;
            }
        }
    }

    private string GetSimpleUserTypeName(IUserDataType userType)
    {
        string typeName = userType.Name;
        if (!string.IsNullOrEmpty(typeName) && typeName.EndsWith("?"))
            typeName = typeName[..^1];
        int lastDotIdx = typeName.LastIndexOf('.');
        if (lastDotIdx >= 0 && lastDotIdx < typeName.Length - 1)
            typeName = typeName[(lastDotIdx + 1)..];
        return typeName.ToPascalCase();
    }

    private string GetBuiltFileNameForUserType(IUserDataType userType)
    {
        if (userType is ObjectType obj)
        {
            return DefinitionBuilder.GetBuiltFileName(new BuildContext(obj.OwnedFile, []), obj.OwnedDefinition);
        }
        if (userType is EnumType en)
        {
            return EnumBuilder.GetBuiltFileName(new BuildContext(en.OwnedFile, []), en.OwnedEnum);
        }
        if (userType is UnionType union)
        {
            return Helpers.FilePathToPascalCase(union.OwnedFile.FilePath) + ".ts";
        }
        // Fallback shouldn't happen
        return string.Empty;
    }

    private void CompileUnions(BuiltFile file, StringBuilder sb)
    {
        foreach (UnionNode union in file.Unions)
        {
            string unionName = union.Name.ToPascalCase();
            List<string> variantNames = union.Variants.Values.Select(GetSimpleUserTypeName).ToList();

            sb.AppendLine();
            AppendDescriptionComment(sb, union);

            if (UsesEffectSchema)
            {
                sb.AppendLine($"export const {unionName} = Schema.Union({string.Join(", ", variantNames)});");
                sb.AppendLine();
                sb.AppendLine($"export type {unionName} = typeof {unionName}.Type;");
            }
            else
            {
                sb.AppendLine($"export type {unionName} = {string.Join(" | ", variantNames)};");
            }
        }
    }

    private static PropertyPresence GetPresence(BuiltProperty property)
    {
        return property.Node is PropertyNode propertyNode ? propertyNode.Presence : PropertyPresence.Default;
    }

    private static string WithoutNull(string typeName)
    {
        return typeName.EndsWith(" | null", StringComparison.Ordinal) ? typeName[..^" | null".Length] : typeName;
    }

    private static string ToStringLiteral(string value)
    {
        return $"\"{value.Replace("\\", "\\\\").Replace("\"", "\\\"")}\"";
    }

    private string ComputeRelativeImportPath(string fromFile, string toFile)
    {
        string fromDir = System.IO.Path.GetDirectoryName(fromFile)?.Replace('\\', '/') ?? string.Empty;
        string toPath = toFile.Replace('\\', '/');
        string rel = System.IO.Path.GetRelativePath(string.IsNullOrEmpty(fromDir) ? "." : fromDir, toPath)
            .Replace('\\', '/');

        // Drop extension
        if (rel.EndsWith(".ts", StringComparison.OrdinalIgnoreCase))
            rel = rel.Substring(0, rel.Length - 3);

        if (!rel.StartsWith(".") && !rel.StartsWith("/"))
            rel = "./" + rel;
        return rel;
    }
