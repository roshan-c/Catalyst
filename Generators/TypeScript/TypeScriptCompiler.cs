using System.Text;
using Catalyst.SpecGraph.Properties;
using Catalyst.SpecGraph.Nodes;

namespace Catalyst.Generators.TypeScript;

public class TypeScriptCompiler : Compiler
{
    public override string Name => TypeScript.Name;

    private readonly TypeScriptSchemaMode _schemaMode;

    public TypeScriptCompiler(CompilerOptions options) : base(options)
    {
        _schemaMode = TypeScriptSchemaModeParser.Parse(options.TypeScriptSchema);
    }

    public bool UsesEffectSchema => _schemaMode is TypeScriptSchemaMode.Effect;

    protected override bool SupportsUnions => true;
    protected override bool SupportsStringEnums => true;
    protected override bool SupportsPropertyPresence => true;

    protected override void BuildUnion(BuildContext context, UnionNode unionNode)
    {
        context.GetOrAddFile(this, Helpers.FilePathToPascalCase(context.FileNode.FilePath) + ".ts").Unions.Add(unionNode);
    }

    private bool UsesSchemaAtRuntime(BuiltFile file)
    {
        return file.Definitions.Count > 0 || file.Unions.Count > 0 ||
               (ClientServiceBuilder is not null && file.Services.Count > 0) ||
               file.Enums.Any(builtEnum => builtEnum.Node.Flags == true || builtEnum.Node.IsString);
    }

    public override CompiledFile Compile(BuiltFile file)
    {
        StringBuilder sb = new();

        sb.AppendLine("//");
        sb.AppendLine($"// This file was generated by Catalyst's TypeScript compiler{GeneratedAt}.");
        sb.AppendLine("// It is recommended not to modify this file. Modify the source spec file instead.");
        sb.AppendLine("//");
        sb.AppendLine();

        bool wroteImport = false;
        if (UsesEffectSchema && UsesSchemaAtRuntime(file))
        {
            sb.AppendLine("import { Schema } from 'effect';");
            wroteImport = true;
        }

        // Emit imports for referenced user-defined types across files
        var importMap = BuildTypeScriptImportMap(file);
        foreach (var import in importMap.OrderBy(kvp => kvp.Key))
        {
            string importPath = ComputeRelativeImportPath(file.Name, import.Key);
            string symbols = string.Join(", ", import.Value.OrderBy(x => x));
            sb.AppendLine($"import {{ {symbols} }} from '{importPath}';");
            wroteImport = true;
        }
        if (wroteImport)
            sb.AppendLine();

        foreach (var builtEnum in file.Enums)
        {
            AppendDescriptionComment(sb, builtEnum.Node);

            if (builtEnum.Node.IsString)
            {
                AppendStringEnum(sb, builtEnum);
                sb.AppendLine();
                continue;
            }

            sb.AppendLine($"export enum {builtEnum.Name} {{");

            for (var enumValueIdx = 0; enumValueIdx < builtEnum.Values.Count; enumValueIdx++)
            {
                BuiltEnumValue builtEnumValue = builtEnum.Values[enumValueIdx];
                sb.Append($"    {builtEnumValue.Label} = {builtEnumValue.Value}");
                if (enumValueIdx < builtEnum.Values.Count - 1)
                    sb.Append(',');
                sb.AppendLine();
            }

            sb.AppendLine("}");

            if (UsesEffectSchema && builtEnum.Node.Flags == true)
                AppendEffectFlagsEnumSchema(sb, builtEnum);

            sb.AppendLine();
        }

        if (UsesEffectSchema)
            CompileEffectDefinitions(file, sb);
        else
            CompileClassDefinitions(file, sb);

        CompileUnions(file, sb);

        if (ClientServiceBuilder is not null)
            foreach (BuiltService service in file.Services)
                ClientServiceBuilder.Compile(file, service, sb);

        return new CompiledFile(file.Name, sb.ToString());
    }

    private void CompileClassDefinitions(BuiltFile file, StringBuilder sb)
    {
        for (var defIdx = 0; defIdx < file.Definitions.Count; defIdx++)
        {
            BuiltDefinition def = file.Definitions[defIdx];

            AppendDescriptionComment(sb, def.Node);
            sb.AppendLine($"export class {def.Name} {{");

            if (def.Node.Union is { } union)
            {
                string tag = ToStringLiteral(def.Node.UnionTag!);
                sb.AppendLine($"    public readonly {GetCompiledPropertyKey(union.Discriminator)}: {tag} = {tag};");
                sb.AppendLine();
            }

            if (def.Constants.Count > 0)
            {
                for (var constantIdx = 0; constantIdx < def.Constants.Count; constantIdx++)
                {
                    BuiltConstant constant = def.Constants[constantIdx];

                    AppendDescriptionComment(sb, constant.Node, 1);

                    sb.Append($"    static readonly {constant.Name}: {constant.Type.Name} = {constant.Value.Value};");

                    sb.AppendLine();

                    if (constantIdx < def.Constants.Count - 1)
                        sb.AppendLine();
                }

                sb.AppendLine();
            }

            for (var propertyIdx = 0; propertyIdx < def.Properties.Count; propertyIdx++)
            {
                BuiltProperty property = def.Properties[propertyIdx];
                bool isOptional = property.Node.BuiltType is IOptionalDataType;
                PropertyPresence presence = GetPresence(property);

                AppendDescriptionComment(sb, property.Node, 1);

                sb.Append("    public ");
                sb.Append(property.Name);
                if (isOptional && presence is not PropertyPresence.Nullable)
                    sb.Append("?");
                sb.Append($": {(presence is PropertyPresence.Optional ? WithoutNull(property.Type.Name) : property.Type.Name)}");

                if (property.Value is SomeDataValue some && !isOptional)
                    sb.Append($" = {some.Value}");
                else if (presence is PropertyPresence.Nullable)
                    sb.Append(" = null");
                sb.AppendLine(";");

                if (propertyIdx < def.Properties.Count - 1)
                    sb.AppendLine();
            }

            foreach (BuiltFunction function in def.Functions)
            {
                sb.AppendLine();

                bool isStatic = function.Flags is FunctionFlags.Static;
                sb.Append("    public ");
                if (isStatic)
                    sb.Append("static ");

                sb.Append($"{function.Name}(");
                for (int parameterIdx = 0; parameterIdx < function.Parameters.Count; parameterIdx++)
                {
                    sb.Append(function.Parameters[parameterIdx]);
                    if (parameterIdx < function.Parameters.Count - 1)
                        sb.Append(", ");
                }
                sb.Append(")");
                if (!string.IsNullOrWhiteSpace(function.ReturnType))
                    sb.Append($": {function.ReturnType}");
                sb.AppendLine();
                sb.AppendLine("    {");
                if (function.Body is not null)
                {
                    string[] lines = function.Body.Split(Environment.NewLine);
                    foreach (string line in lines)
                        sb.AppendLine($"        {line}");
                }
                sb.AppendLine("    }");
            }

            // Default serialisation helpers if none provided
            if (!def.Functions.Any(f => f.Name == "toBytes"))
            {
                sb.AppendLine();
                sb.AppendLine("    public toBytes(): Uint8Array");
                sb.AppendLine("    {");
                sb.AppendLine("        const json = JSON.stringify(this);");
                sb.AppendLine("        return new TextEncoder().encode(json);");
                sb.AppendLine("    }");
            }
            if (!def.Functions.Any(f => f.Name == "fromBytes"))
            {
                sb.AppendLine();
                sb.AppendLine($"    public static fromBytes(bytes: Uint8Array): {def.Name} | null");
                sb.AppendLine("    {");
                sb.AppendLine("        try {");
                sb.AppendLine("            const json = new TextDecoder().decode(bytes);");
                sb.AppendLine($"            const obj = JSON.parse(json) as {def.Name};");
                sb.AppendLine($"            return Object.assign(new {def.Name}(), obj);");
                sb.AppendLine("        } catch { return null; }");
                sb.AppendLine("    }");
            }

            sb.AppendLine("}");

            if (defIdx < file.Definitions.Count - 1)
                sb.AppendLine();
        }
    }

    /// <summary>
    /// A string enum is a const object of its values plus the union of their literal types,
    /// rather than a TS <c>enum</c>: a string <c>enum</c> refuses comparisons with plain string
    /// literals, which is how wire values are usually checked. In Effect Schema mode a
    /// <c>{Name}Schema</c> validates the values.
    /// </summary>
    private void AppendStringEnum(StringBuilder sb, BuiltEnum builtEnum)
    {
        List<string> wireValues = builtEnum.Values
            .Select(value => ToStringLiteral(builtEnum.Node.WireValues[value.Label]))
            .ToList();

        sb.AppendLine($"export const {builtEnum.Name} = {{");
        for (var valueIdx = 0; valueIdx < builtEnum.Values.Count; valueIdx++)
        {
            sb.Append($"    {GetStringEnumMemberName(builtEnum.Values[valueIdx].Label)}: {wireValues[valueIdx]}");
            if (valueIdx < builtEnum.Values.Count - 1)
                sb.Append(',');
            sb.AppendLine();
        }
        sb.AppendLine("} as const;");
        sb.AppendLine();
        sb.AppendLine($"export type {builtEnum.Name} = (typeof {builtEnum.Name})[keyof typeof {builtEnum.Name}];");

        if (UsesEffectSchema)
        {
            sb.AppendLine();
            sb.AppendLine($"export const {builtEnum.Name}Schema = Schema.Literal({string.Join(", ", wireValues)});");
        }
    }

    /// <summary>
    /// A string enum's member name: its label in PascalCase, since a bare value such as
    /// <c>net_worth</c> is both the label and the wire value.
    /// </summary>
    public string GetStringEnumMemberName(string label)
    {
        return GetCompiledPropertyKey(label.ToPascalCase());
    }

    private static void AppendEffectFlagsEnumSchema(StringBuilder sb, BuiltEnum builtEnum)
    {
        // Schema.Enums only accepts the declared members, but a flags enum can hold any
        // combination of its bits (and often -1 for 'all'). Validate the bits instead.
        int mask = 0;
        foreach (BuiltEnumValue value in builtEnum.Values)
        {
            if (value.Value >= 0)
                mask |= value.Value;
        }

        sb.AppendLine();
        sb.AppendLine($"export const {builtEnum.Name}Schema = Schema.Int.pipe(");
        sb.AppendLine($"    Schema.filter((value): value is {builtEnum.Name} => value === -1 || (value & ~{mask}) === 0)");
        sb.AppendLine(");");
    }

    private void CompileEffectDefinitions(BuiltFile file, StringBuilder sb)
    {
        for (var defIdx = 0; defIdx < file.Definitions.Count; defIdx++)
        {
            BuiltDefinition def = file.Definitions[defIdx];
            bool isRecursive = IsRecursiveDefinition(def);

            AppendDescriptionComment(sb, def.Node);

            if (isRecursive)
            {
                // A recursive schema cannot infer its own type, so give it an explicit interface.
                AppendEffectInterface(sb, def);
            }

            string declaration = isRecursive
                ? $"export const {def.Name}: Schema.Schema<{def.Name}> = "
                : $"export const {def.Name} = ";

            List<string> leadingFields = [];
            if (def.Node.Union is { } union)
            {
                leadingFields.Add(
                    $"    {GetCompiledPropertyKey(union.Discriminator)}: Schema.Literal({ToStringLiteral(def.Node.UnionTag!)})");
            }

            if (def.Properties.Count == 0 && leadingFields.Count == 0)
            {
                sb.AppendLine($"{declaration}Schema.Struct({{}});");
            }
            else
            {
                sb.AppendLine($"{declaration}Schema.Struct({{");

                for (var leadingIdx = 0; leadingIdx < leadingFields.Count; leadingIdx++)
                {
                    sb.Append(leadingFields[leadingIdx]);
                    if (leadingIdx < leadingFields.Count - 1 || def.Properties.Count > 0)
                        sb.Append(',');
                    sb.AppendLine();
                }

                for (var propertyIdx = 0; propertyIdx < def.Properties.Count; propertyIdx++)
                {
                    BuiltProperty property = def.Properties[propertyIdx];

                    AppendDescriptionComment(sb, property.Node, 1);

                    sb.Append($"    {GetCompiledPropertyKey(property.Node.Name)}: {GetSchemaPropertyExpression(property)}");
                    if (propertyIdx < def.Properties.Count - 1)
                        sb.Append(',');
                    sb.AppendLine();
                }

                sb.AppendLine("});");
            }

            if (!isRecursive)
            {
                sb.AppendLine();
                sb.AppendLine($"export type {def.Name} = typeof {def.Name}.Type;");
            }

            if (def.Constants.Count > 0)
            {
                sb.AppendLine();
                AppendEffectConstants(sb, def);
            }

            if (defIdx < file.Definitions.Count - 1)
                sb.AppendLine();
        }
    }

    private void AppendEffectInterface(StringBuilder sb, BuiltDefinition def)
    {
        sb.AppendLine($"export interface {def.Name} {{");

        if (def.Node.Union is { } union)
            sb.AppendLine($"    readonly {GetCompiledPropertyKey(union.Discriminator)}: {ToStringLiteral(def.Node.UnionTag!)};");

        foreach (BuiltProperty property in def.Properties)
        {
            AppendDescriptionComment(sb, property.Node, 1);

            bool isOptional = property.Node.BuiltType is IOptionalDataType;
            PropertyPresence presence = GetPresence(property);
            sb.Append($"    readonly {GetCompiledPropertyKey(property.Node.Name)}");
            if (isOptional && presence is not PropertyPresence.Nullable)
                sb.Append('?');
            string typeName = presence is PropertyPresence.Optional ? WithoutNull(property.Type.Name) : property.Type.Name;
            sb.AppendLine($": {typeName};");
        }

        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static bool IsRecursiveDefinition(BuiltDefinition definition)
    {
        return definition.Properties.Any(property =>
            ReachesDefinition(property.Node.BuiltType!, definition.Node, new HashSet<DefinitionNode>()));
    }

    private static bool ReachesDefinition(IDataType dataType, DefinitionNode target, HashSet<DefinitionNode> visited)
    {
        switch (dataType)
        {
            case ListType listType:
                return ReachesDefinition(listType.InnerType, target, visited);
            case SetType setType:
                return ReachesDefinition(setType.InnerType, target, visited);
            case MapType mapType:
                return ReachesDefinition(mapType.InnerTypeA, target, visited) ||
                       ReachesDefinition(mapType.InnerTypeB, target, visited);
            case UnionType unionType:
                return unionType.OwnedUnion.Variants.Values.Any(variant => ReachesDefinition(variant, target, visited));
            case ObjectType objectType:
                DefinitionNode definition = objectType.OwnedDefinition;
                if (ReferenceEquals(definition, target))
                    return true;
                if (!visited.Add(definition))
                    return false;
                return definition.Properties.Any(property =>
                    ReachesDefinition(property.Value.BuiltType!, target, visited));
            default:
                return false;
        }
    }

    private void AppendEffectConstants(StringBuilder sb, BuiltDefinition def)
    {
        sb.AppendLine($"export const {def.Name}Constants = {{");

        for (var constantIdx = 0; constantIdx < def.Constants.Count; constantIdx++)
        {
            BuiltConstant constant = def.Constants[constantIdx];

            AppendDescriptionComment(sb, constant.Node, 1);

            string value = constant.Value.Value ?? "undefined";
            sb.Append($"    {GetCompiledPropertyKey(constant.Name)}: {value}");
            if (constantIdx < def.Constants.Count - 1)
                sb.Append(',');
            sb.AppendLine();
        }

        sb.AppendLine("} as const;");
    }

